"""Regenerates ArkEmblemGeometry.cs from the brand package (never hand-edit the C# file).

Sources (@ark/packages/ui/src/brand):
- ark-emblem-geometry.ts: the cube emblem (ArkMark) paths, 2000 x 2000.
- assets/ark-lockup/ark-aperture-favicon-16.svg and -32.svg: the aperture favicon, the small-size
  drawing the design system ratified for tabs and trays. The tile <rect> is dropped; the A path and
  the globe circle are kept.
Run: python tools/gen_emblem_geometry.py (from the omniwand folder)
"""
import pathlib
import re

BRAND = pathlib.Path("@ark/packages/ui/src/brand")
OUT = pathlib.Path(__file__).resolve().parent.parent / "ArkEmblemGeometry.cs"


def cube():
    src = (BRAND / "ark-emblem-geometry.ts").read_text(encoding="utf-8")
    cube_path = re.search(r'ARK_EMBLEM_CUBE_PATH =\s*"([^"]+)"', src).group(1)
    globe_path = re.search(r'ARK_EMBLEM_GLOBE_PATH =\s*"([^"]+)"', src).group(1)
    stubs = re.findall(r'^\s*"(M[^"]+)",\s*$', src, re.M)
    assert len(stubs) == 3, stubs
    return cube_path, stubs, globe_path


def aperture(size: int):
    svg = (BRAND / f"assets/ark-lockup/ark-aperture-favicon-{size}.svg").read_text(encoding="utf-8")
    a_path = re.search(r'<path[^>]*\sd="([^"]+)"', svg).group(1)
    c = re.search(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"', svg)
    return a_path, tuple(float(v) for v in c.groups())


def main() -> None:
    cube_path, stubs, globe_path = cube()
    a16, g16 = aperture(16)
    a32, g32 = aperture(32)
    stub_lines = "".join(f'        "{s}",\n' for s in stubs)
    out = f'''// Generated by tools/gen_emblem_geometry.py from @ark/packages/ui/src/brand.
// Do not edit: rerun the script when the brand geometry changes.
namespace Omniwand;

internal static class ArkEmblemGeometry
{{
    // Cube emblem (ArkMark), source ark-emblem-geometry.ts. Canva DAHSV7I81c8 "Ark Emblem" is the source of record.
    public const float ViewBox = 2000f;
    public const string CubePath = "{cube_path}";
    public static readonly string[] StubPaths =
    {{
{stub_lines}    }};
    public const string GlobePath = "{globe_path}";

    // Aperture favicon (ratified 2026-10-02), the small-size drawing for tabs and trays. Tile rect dropped.
    public const float Aperture16ViewBox = 16f;
    public const string Aperture16Path = "{a16}";
    public static readonly float[] Aperture16Globe = {{ {g16[0]}f, {g16[1]}f, {g16[2]}f }};
    public const float Aperture32ViewBox = 32f;
    public const string Aperture32Path = "{a32}";
    public static readonly float[] Aperture32Globe = {{ {g32[0]}f, {g32[1]}f, {g32[2]}f }};
}}
'''
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: cube {len(cube_path)}, aperture16 {len(a16)}, aperture32 {len(a32)}, globes {g16} {g32}")


if __name__ == "__main__":
    main()
