"""Regenerates PhosphorTokens.cs from @ark/tokens (never hand-edit the C# file).

Source (@ark/packages/tokens/src), the only design source of truth (Ark CLAUDE.md rule 13):
- colors.css, spacing.css, typography.css: the first :root block of each.
Only plain values are carried: hex colors, px and em lengths, ms durations and bare numbers.
Aliases (var(...)), rgba, gradients, shadows and font stacks are skipped; Omniwand has no use for them yet.
PhosphorTheme reads these values at runtime; the UI Lab overlays edits on top and exports a patch
against the same files, so nothing is ever written back silently.
Run: python tools/gen_phosphor_tokens.py (from the omniwand folder)
"""
import pathlib
import re

TOKENS = pathlib.Path("@ark/packages/tokens/src")
FILES = ["colors.css", "spacing.css", "typography.css"]
OUT = pathlib.Path(__file__).resolve().parent.parent / "PhosphorTokens.cs"

PLAIN = re.compile(r"^(#[0-9a-fA-F]{3,8}|-?\d+(\.\d+)?(px|em|ms)?)$")
DECL = re.compile(r"--([\w-]+)\s*:\s*([^;]+);[ \t]*(/\*(.*?)\*/)?")


def root_block(css: str) -> str:
    start = css.index(":root")
    depth = 0
    for i in range(css.index("{", start), len(css)):
        if css[i] == "{":
            depth += 1
        elif css[i] == "}":
            depth -= 1
            if depth == 0:
                return css[start:i]
    raise ValueError("unclosed :root")


def cs(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> None:
    rows = []
    for name in FILES:
        block = root_block((TOKENS / name).read_text(encoding="utf-8"))
        for m in DECL.finditer(block):
            value = " ".join(m.group(2).split())
            if not PLAIN.match(value):
                continue
            note = " ".join((m.group(4) or "").split())
            rows.append((m.group(1), value, name, note))
    lines = "".join(f'        new("{n}", "{cs(v)}", "{f}", "{cs(c)}"),\n' for n, v, f, c in rows)
    out = f'''// Generated by tools/gen_phosphor_tokens.py from @ark/packages/tokens/src.
// Do not edit: rerun the script when the tokens change. PhosphorTheme resolves every value from here.
namespace Omniwand;

internal static class PhosphorTokens
{{
    public const string SourceRoot = "@ark";
    public const string SourceDir = "packages/tokens/src";

    public static readonly PhosphorToken[] All =
    {{
{lines}    }};
}}
'''
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(rows)} tokens from {', '.join(FILES)}")


if __name__ == "__main__":
    main()
