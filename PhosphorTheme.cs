    public static GraphicsPath CreateRoundedRect(RectangleF bounds, float radius)
    {
        var path = new GraphicsPath();
        if (radius <= 0.5f || bounds.Width <= 2f || bounds.Height <= 2f)
        {
            path.AddRectangle(bounds);
            return path;
        }
        float d = Math.Min(radius * 2f, Math.Min(bounds.Width, bounds.Height));
        path.AddArc(bounds.X, bounds.Y, d, d, 180, 90);
        path.AddArc(bounds.Right - d, bounds.Y, d, d, 270, 90);
        path.AddArc(bounds.Right - d, bounds.Bottom - d, d, d, 0, 90);
        path.AddArc(bounds.X, bounds.Bottom - d, d, d, 90, 90);
        path.CloseFigure();
        return path;
    }

    /// <summary>
    /// Renders a canonical Phosphor Shell panel (#121212 surface, #262626 border, top specular hairline).
    /// </summary>
    public static void DrawPhosphorPanel(Graphics g, Rectangle bounds, int radius = -1, Color? fillOverride = null, Color? borderOverride = null)
    {
        if (radius < 0) radius = RadiusWidget;
        g.SmoothingMode = SmoothingMode.AntiAlias;
        var rect = new RectangleF(bounds.X + 0.5f, bounds.Y + 0.5f, bounds.Width - 1f, bounds.Height - 1f);
        using var path = CreateRoundedRect(rect, radius);
        using var fill = new SolidBrush(fillOverride ?? Surface);
        using var border = new Pen(borderOverride ?? Line, 1f);
        g.FillPath(fill, path);
        g.DrawPath(border, path);

        // Subtle top-edge phosphor hairline (rgba(255,255,255,0.04))
        using var topPen = new Pen(Color.FromArgb(12, 255, 255, 255), 1f);
        g.DrawLine(topPen, bounds.X + radius, bounds.Y + 1, bounds.Right - radius, bounds.Y + 1);
    }

    /// <summary>
    /// Implements Veritas `highlight-aura-rule`:
    /// Leading-edge 2px inset bar + 12px (--aura-lead) gap + gradient bloom that fades out before the right edge (65% -> 90%).
    /// Masks only decoration, never text or hit targets.
    /// </summary>
    public static void DrawHighlightAura(Graphics g, Rectangle bounds, Color sidelight, float intensity = 1.0f, int radius = -1)
    {
        // Mirrors packages/ui/src/surfaces/aura.css (.rp-aura): a surface-2 fill, an inset 2px side light the
        // full height of the leading edge, an inner bloom (inset 12px 0 16px -8px at 28%), all faded through
        // --aura-falloff (opaque to 65% of the width, gone by 90%). The outer -2px glow is left out: hosts clip
        // their rows, so it never shows. intensity scales the light, not the fill.
        if (radius < 0) radius = RadiusTile;
        if (bounds.Width <= 4 || bounds.Height <= 4 || intensity <= 0.01f) return;
        g.SmoothingMode = SmoothingMode.AntiAlias;

        using var clipPath = CreateRoundedRect(bounds, radius);
        var prevClip = g.Clip;
        g.SetClip(clipPath, CombineMode.Intersect);

        // --aura-falloff: full to 65%, transparent by 90%.
        float[] falloffAt = { 0f, 0.65f, 0.90f, 1f };
        LinearGradientBrush Falloff(Color c, int alpha)
        {
            var brush = new LinearGradientBrush(new Rectangle(bounds.Left - 1, bounds.Top, bounds.Width + 2, bounds.Height),
                Color.FromArgb(alpha, c), Color.FromArgb(0, c), LinearGradientMode.Horizontal);
            brush.InterpolationColors = new ColorBlend(4)
            {
                Colors = new[] { Color.FromArgb(alpha, c), Color.FromArgb(alpha, c), Color.FromArgb(0, c), Color.FromArgb(0, c) },
                Positions = falloffAt
            };
            return brush;
        }

        using (var fill = Falloff(Surface2, 255))
            g.FillRectangle(fill, bounds);

        // Inner bloom: inset shadow offset 12px, blur 16px, spread -8px -> a glow from the leading edge that is
        // gone about 20px in, softer toward the top and bottom.
        int bloomAlpha = (int)Math.Clamp(0.28f * 255 * intensity, 0, 255);
        int bloomW = Math.Min(bounds.Width, S5);
        var bloomRect = new Rectangle(bounds.Left, bounds.Top, bloomW, bounds.Height);
        using (var bloom = new LinearGradientBrush(new Rectangle(bloomRect.Left - 1, bloomRect.Top, bloomRect.Width + 1, bloomRect.Height),
            Color.FromArgb(bloomAlpha, sidelight), Color.FromArgb(0, sidelight), LinearGradientMode.Horizontal))
        {
            g.FillRectangle(bloom, bloomRect);
        }

        // Side light: inset calc(var(--u) / 2), the full height of the leading edge.
        using (var bar = new SolidBrush(Color.FromArgb((int)Math.Clamp(255 * intensity, 0, 255), sidelight)))
            g.FillRectangle(bar, bounds.Left, bounds.Top, 2, bounds.Height);

        g.Clip = prevClip;
    }

