    private static volatile Dictionary<string, string> Values = BuildValues();
    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, Color> ColorCache = new(StringComparer.Ordinal);

    private static Dictionary<string, string> BuildValues()
    {
        var d = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var t in PhosphorTokens.All) d[t.Name] = t.Value;
        foreach (var l in Locals) d[l.Name] = l.Value;
        foreach (var (k, v) in PhosphorTuning.Read())
            if (d.ContainsKey(k)) d[k] = v;
        return d;
    }

    /// <summary>Rebuilds the table from the tokens, the locals and the tuning overlay, then raises <see cref="Tuned"/>.</summary>
    internal static void ReloadTuning()
    {
        Values = BuildValues();
        ColorCache.Clear();
        Tuned?.Invoke();
    }

    /// <summary>Raised after the tuning overlay changed, on whatever thread noticed it.</summary>
    internal static event Action? Tuned;

    /// <summary>A token value by CSS name without the leading dashes ("radius-btn"), or a Local.</summary>
    internal static string Value(string name) => Values.TryGetValue(name, out var v) ? v : string.Empty;

    /// <summary>A token color by CSS name without the leading dashes ("color-bone").</summary>
    public static Color C(string name) => ColorCache.GetOrAdd(name, n => TryParseColor(Value(n), out var c) ? c : Color.Magenta);

    /// <summary>Numeric part of a px, em, ms or bare value.</summary>
    public static float N(string name) => ParseNumber(Value(name));

    public static int Px(string name) => (int)Math.Round(N(name));

    internal static float ParseNumber(string v)
    {
        int end = 0;
        while (end < v.Length && (char.IsDigit(v[end]) || v[end] is '.' or '-')) end++;
        return float.TryParse(v.AsSpan(0, end), System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var f) ? f : 0f;
    }

    internal static bool TryParseColor(string? value, out Color color)
    {
        color = Color.Empty;
        if (string.IsNullOrWhiteSpace(value)) return false;
        string v = value.Trim();
        if (!v.StartsWith('#')) return false;
        string hex = v[1..];
        if (hex.Length == 3) hex = string.Concat(hex[0], hex[0], hex[1], hex[1], hex[2], hex[2]);
        if (hex.Length is not (6 or 8) || !uint.TryParse(hex, System.Globalization.NumberStyles.HexNumber, null, out _)) return false;
        int r = Convert.ToInt32(hex[..2], 16), g = Convert.ToInt32(hex[2..4], 16), b = Convert.ToInt32(hex[4..6], 16);
        int a = hex.Length == 8 ? Convert.ToInt32(hex[6..8], 16) : 255;
        color = Color.FromArgb(a, r, g, b);
        return true;
    }

