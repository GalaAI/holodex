    /// <summary>
    /// Implements Veritas `scroll-indicator-rule`:
    /// Darker overlay thumb, no tracks or arrows, no reserved layout width, 500ms idle fade.
    /// </summary>
    public static void DrawScrollAffordanceThumb(
        Graphics g,
        Rectangle container,
        float scrollRatio,
        float viewportRatio,
        float opacity = 0.85f)
    {
        if (viewportRatio >= 0.99f || opacity <= 0.02f) return;
        int trackHeight = container.Height - 12;
        if (trackHeight <= 16) return;

        int thumbHeight = Math.Max(24, (int)(trackHeight * Math.Clamp(viewportRatio, 0.08f, 1.0f)));
        int maxTravel = Math.Max(0, trackHeight - thumbHeight);
        int thumbTop = container.Top + 6 + (int)(maxTravel * Math.Clamp(scrollRatio, 0f, 1f));
        var thumbRect = new RectangleF(container.Right - 7, thumbTop, 4f, thumbHeight);

        int alpha = (int)Math.Clamp(opacity * 210, 0, 255);
        using var path = CreateRoundedRect(thumbRect, 2f);
        using var fill = new SolidBrush(Color.FromArgb(alpha, 35, 35, 34));
        using var border = new Pen(Color.FromArgb((int)(alpha * 0.7f), Line2), 1f);
        g.FillPath(fill, path);
        g.DrawPath(border, path);
    }
