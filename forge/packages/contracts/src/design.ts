import { z } from "zod";
import { agentIdSchema } from "./agents.js";
import {
  annotationIdSchema,
  buildIdSchema,
  componentIdSchema,
  designSystemIdSchema,
  isoDateTimeSchema,
  tweakIdSchema,
} from "./common.js";

/**
 * Design system, component inventory, tweaks and annotations (SPEC flow
 * steps 5 and 7). UX reference: Claude Design, a canvas spread of
 * artboards with inline comments and tweak panels.
 *
 * These describe the user's BUILD, so token values here are data (a hex
 * color is a value the user picked), not styling for 4GE's own components.
 */

const tokenName = z.string().min(1).max(80);

export const designTokensSchema = z.object({
  colors: z
    .array(
      z.object({
        name: tokenName,
        value: z.string().min(1).max(80),
        role: z
          .enum(["background", "surface", "text", "muted", "primary", "accent", "success", "warning", "danger", "border", "other"])
          .default("other"),
      }),
    )
    .max(80)
    .default([]),
  typography: z
    .array(
      z.object({
        name: tokenName,
        family: z.string().min(1).max(200),
        size: z.string().min(1).max(40),
        weight: z.number().int().min(100).max(1000).default(400),
        lineHeight: z.string().max(40).optional(),
        tracking: z.string().max(40).optional(),
      }),
    )
    .max(40)
    .default([]),
  spacing: z.array(z.object({ name: tokenName, value: z.string().min(1).max(40) })).max(40).default([]),
  radii: z.array(z.object({ name: tokenName, value: z.string().min(1).max(40) })).max(20).default([]),
  shadows: z.array(z.object({ name: tokenName, value: z.string().min(1).max(400) })).max(20).default([]),
  motion: z
    .array(
      z.object({
        name: tokenName,
        durationMs: z.number().int().min(0).max(20_000),
        easing: z.string().min(1).max(120),
      }),
    )
    .max(20)
    .default([]),
});
export type DesignTokens = z.infer<typeof designTokensSchema>;

export const designSystemSchema = z.object({
  id: designSystemIdSchema,
  buildId: buildIdSchema,
  name: z.string().min(1).max(160),
  /** Where the system came from: 4GE's kit, generated by Smith, or imported. */
  source: z.enum(["kit", "generated", "imported"]),
  tokens: designTokensSchema,
  /** Plain-words principles Smith and the user agreed on. */
  principles: z.array(z.string().min(1).max(400)).max(20).default([]),
  updatedAt: isoDateTimeSchema,
});
export type DesignSystem = z.infer<typeof designSystemSchema>;

export const componentCategorySchema = z.enum([
  "layout",
  "navigation",
  "input",
  "display",
  "feedback",
  "media",
  "commerce",
  "booking",
  "content",
  "other",
]);

export const componentInventoryItemSchema = z.object({
  id: componentIdSchema,
  buildId: buildIdSchema,
  name: z.string().min(1).max(120),
  category: componentCategorySchema,
  status: z.enum(["proposed", "accepted", "built", "rejected"]),
  description: z.string().min(1).max(1200),
  /** kit = @4ge/kit, 21st = the 21st registry, generated, or custom. */
  source: z.enum(["kit", "21st", "generated", "custom"]),
  /** Registry id, kit export name or build-relative path. */
  sourceRef: z.string().max(400).optional(),
  /** Build-relative path of a rendered preview. */
  previewRef: z.string().max(400).optional(),
  /** Pages or routes in the build that use it. */
  usedIn: z.array(z.string().min(1).max(200)).max(80).default([]),
  updatedAt: isoDateTimeSchema,
});
export type ComponentInventoryItem = z.infer<typeof componentInventoryItemSchema>;

/** Where on the build a tweak or annotation lands. */
export const designTargetSchema = z.object({
  /** CSS selector or a data-4ge-id in the build's DOM. */
  selector: z.string().min(1).max(600),
  /** Route or page, e.g. "/" or "/booking". */
  page: z.string().max(400).default("/"),
  label: z.string().max(160).optional(),
});
export type DesignTarget = z.infer<typeof designTargetSchema>;

const tweakBase = { buildId: buildIdSchema, target: designTargetSchema };

export const TWEAK_KINDS = [
  "color",
  "placement",
  "layout",
  "text",
  "animation",
  "motion",
  "transition",
  "asset",
  "component",
] as const;
export const tweakKindSchema = z.enum(TWEAK_KINDS);
export type TweakKind = z.infer<typeof tweakKindSchema>;

export const tweakOpSchema = z.discriminatedUnion("kind", [
  z.object({
    ...tweakBase,
    kind: z.literal("color"),
    property: z.enum(["color", "background", "border-color", "fill", "stroke", "token"]),
    /** A color value, or a design token name when property is token. */
    value: z.string().min(1).max(120),
    tokenName: z.string().max(80).optional(),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("placement"),
    x: z.number().optional(),
    y: z.number().optional(),
    align: z.enum(["start", "center", "end", "stretch"]).optional(),
    order: z.number().int().optional(),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("layout"),
    display: z.enum(["block", "flex", "grid", "none"]).optional(),
    direction: z.enum(["row", "column"]).optional(),
    gap: z.string().max(40).optional(),
    columns: z.number().int().min(1).max(24).optional(),
    padding: z.string().max(80).optional(),
    width: z.string().max(40).optional(),
  }),
  z.object({ ...tweakBase, kind: z.literal("text"), text: z.string().max(20_000) }),
  z.object({
    ...tweakBase,
    kind: z.literal("animation"),
    name: z.string().min(1).max(80),
    durationMs: z.number().int().min(0).max(60_000),
    easing: z.string().max(120).default("ease-out"),
    delayMs: z.number().int().min(0).max(60_000).default(0),
    iterations: z.union([z.number().int().min(1).max(1000), z.literal("infinite")]).default(1),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("motion"),
    /** A motion preset name, e.g. fade-up, parallax, hover-lift. */
    preset: z.string().min(1).max(80),
    intensity: z.number().min(0).max(1).default(0.5),
    respectReducedMotion: z.boolean().default(true),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("transition"),
    property: z.string().min(1).max(80),
    durationMs: z.number().int().min(0).max(10_000),
    easing: z.string().max(120).default("ease"),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("asset"),
    /** Build-relative path or URL of the new asset. */
    assetRef: z.string().min(1).max(1000),
    alt: z.string().max(400).optional(),
  }),
  z.object({
    ...tweakBase,
    kind: z.literal("component"),
    action: z.enum(["swap", "insert", "remove"]),
    componentId: componentIdSchema.optional(),
    props: z.record(z.string(), z.unknown()).optional(),
  }),
]);
export type TweakOp = z.infer<typeof tweakOpSchema>;

export const appliedTweakSchema = z.object({
  id: tweakIdSchema,
  op: tweakOpSchema,
  status: z.enum(["pending", "applied", "failed", "reverted"]),
  by: z.union([z.literal("user"), agentIdSchema]),
  /** Build-relative files the tweak changed. */
  changedFiles: z.array(z.string().max(400)).default([]),
  error: z.string().max(2000).optional(),
  createdAt: isoDateTimeSchema,
  appliedAt: isoDateTimeSchema.optional(),
});
export type AppliedTweak = z.infer<typeof appliedTweakSchema>;

export const annotationDraftSchema = z.object({
  buildId: buildIdSchema,
  target: designTargetSchema.extend({
    /** Pin position on the artboard, 0 to 1 of width and height. */
    x: z.number().min(0).max(1).optional(),
    y: z.number().min(0).max(1).optional(),
  }),
  body: z.string().trim().min(1).max(4000),
});
export type AnnotationDraft = z.infer<typeof annotationDraftSchema>;

export const annotationSchema = annotationDraftSchema.extend({
  id: annotationIdSchema,
  author: z.union([z.literal("user"), agentIdSchema]),
  status: z.enum(["open", "resolved"]),
  replies: z
    .array(
      z.object({
        author: z.union([z.literal("user"), agentIdSchema]),
        body: z.string().min(1).max(4000),
        at: isoDateTimeSchema,
      }),
    )
    .default([]),
  createdAt: isoDateTimeSchema,
  resolvedAt: isoDateTimeSchema.optional(),
});
export type Annotation = z.infer<typeof annotationSchema>;

/**
 * A component the inventory picker can offer (added by the design layer).
 * Every candidate records where it came from: 4GE's own kit exports, a
 * dated snapshot of the 21st registry catalog, or a live 21st CLI search.
 */
export const componentCandidateSchema = z.object({
  /** Stable key: "kit:<ExportName>" or "21st:<author>/<slug>". */
  key: z.string().min(1).max(200),
  name: z.string().min(1).max(120),
  category: componentCategorySchema,
  description: z.string().max(1200).default(""),
  source: z.enum(["kit", "21st"]),
  /** Kit export name, or the 21st registry ref "<author>/<slug>". */
  sourceRef: z.string().min(1).max(400),
  sourceUrl: z.string().url().optional(),
  author: z.string().max(120).optional(),
  previewUrl: z.string().url().optional(),
  /** How to add it to a build, e.g. the shadcn add line the registry publishes. */
  installCommand: z.string().max(600).optional(),
  /** kit = @4ge/kit exports, 21st-snapshot = a dated catalog search, 21st-live = the 21st CLI just now. */
  via: z.enum(["kit", "21st-snapshot", "21st-live"]),
  fetchedAt: isoDateTimeSchema.optional(),
});
export type ComponentCandidate = z.infer<typeof componentCandidateSchema>;

export const componentCandidatesResponseSchema = z.object({
  candidates: z.array(componentCandidateSchema),
  /** Whether a live 21st registry search ran, and plain words about it. */
  registry: z.object({ live: z.boolean(), message: z.string().max(600) }),
});
export type ComponentCandidatesResponse = z.infer<typeof componentCandidatesResponseSchema>;
